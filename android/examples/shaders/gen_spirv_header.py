#!/usr/bin/env python3
"""Regenerates ../castles_spirv.h from castles.vert/castles.frag (world +
HUD + unit rendering) and castles_nav.comp (GPU flow-field pathfinding).

Dev-time only (needs glslangValidator); the generated header is checked
in so building the APK never needs any shader tooling. Arrays are filled
by runtime assignment, not brace initializers: squash only expands brace
initializers up to 256 elements, and non-zero global initializers are
unreliable on the ARM64/Android backend. The assignments are split into
part functions because squash also caps a block at 1024 statements."""
import os, struct, subprocess, sys, tempfile

here = os.path.dirname(os.path.abspath(__file__))
out_path = os.path.join(here, '..', 'castles_spirv.h')

def compile_words(src):
    with tempfile.TemporaryDirectory() as td:
        spv = os.path.join(td, 'out.spv')
        subprocess.check_call(['glslangValidator', '-V', src, '-o', spv],
                              stdout=subprocess.DEVNULL)
        data = open(spv, 'rb').read()
    return struct.unpack('<%dI' % (len(data) // 4), data)

vert = compile_words(os.path.join(here, 'castles.vert'))
frag = compile_words(os.path.join(here, 'castles.frag'))
nav = compile_words(os.path.join(here, 'castles_nav.comp'))

lines = ['/* Generated by android/examples/shaders/gen_spirv_header.py from',
         ' * castles.vert / castles.frag / castles_nav.comp via glslangValidator',
         ' * -- do not edit. */',
         '#include <stdint.h>', '',
         'static uint32_t g_castles_vert_spv[%d];' % len(vert),
         'static uint32_t g_castles_frag_spv[%d];' % len(frag),
         'static uint32_t g_castles_nav_spv[%d];' % len(nav), '',
         '']
# squash caps a block at 1024 statements, so the assignments are split
# across several part functions called from init_castles_spirv().
PART = 512
parts = []
for name, words in (('g_castles_vert_spv', vert), ('g_castles_frag_spv', frag),
                    ('g_castles_nav_spv', nav)):
    for start in range(0, len(words), PART):
        fn = 'init_castles_spirv_part%d' % len(parts)
        parts.append(fn)
        lines.append('static void %s(void) {' % fn)
        for i in range(start, min(start + PART, len(words))):
            lines.append('    %s[%d] = 0x%08xu;' % (name, i, words[i]))
        lines.append('}')
        lines.append('')
lines.append('static void init_castles_spirv(void) {')
for fn in parts:
    lines.append('    %s();' % fn)
lines.append('}')
open(out_path, 'w').write('\n'.join(lines) + '\n')
print('wrote %s (%d + %d + %d words)' % (out_path, len(vert), len(frag), len(nav)))
